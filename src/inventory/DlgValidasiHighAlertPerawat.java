    private void simpan() {
        if (tbResep.getSelectedRow() < 0 || kdValidasiTersimpan.isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "Pilih resep High Alert yang akan divalidasi..!!");
            return;
        }
        if (!akses.getkode().equals("Admin Utama")) {
            aturPetugas();
        }
        if (KdPetugas.getText().trim().isEmpty() || NmPetugas.getText().trim().isEmpty()) {
            Valid.textKosong(BtnPetugas, "Perawat Validasi");
            return;
        }
        if (!rbSesuai.isSelected() && !rbPerubahanDosis.isSelected()) {
            JOptionPane.showMessageDialog(rootPane, "Pilih Sesuai atau Perubahan dosis..!!");
            return;
        }

        String instruksi = rbSesuai.isSelected() ? "sesuai" : "perubahan_dosis";
        String[] nilai = new String[]{
            TKeterangan.getText(),
            KdPetugas.getText(),
            instruksi,
            cekPasien.isSelected() ? "1" : "0",
            cekObat.isSelected() ? "1" : "0",
            cekDosis.isSelected() ? "1" : "0",
            cekRutePemberian.isSelected() ? "1" : "0",
            cekFrekuensi.isSelected() ? "1" : "0",
            kdValidasiTersimpan
        };
        try {
            Sequel.AutoComitFalse();
            boolean berhasil = Sequel.queryu2tf(
                    "update " + TBL_HEADER + " set keterangan_kegiatan=?,nip_petugas2=?,"
                    + "obat_sesuai_instruksi=?,cek_pasien=?,cek_obat=?,cek_dosis=?,"
                    + "cek_rute_pemberian=?,cek_frekuensi=?,validasi_petugas2=1 "
                    + "where kd_validasi=?", 9, nilai);
            if (berhasil) {
                Sequel.Commit();
                JOptionPane.showMessageDialog(rootPane, "Validasi perawat berhasil disimpan..!!");
            } else {
                Sequel.RollBack();
                JOptionPane.showMessageDialog(rootPane, "Validasi perawat gagal disimpan. Perubahan dibatalkan..!!");
            }
        } catch (Exception e) {
            Sequel.RollBack();
            System.out.println("Gagal menyimpan validasi perawat High Alert: " + e);
            JOptionPane.showMessageDialog(rootPane, "Gagal menyimpan validasi perawat:\n" + e.getMessage());
        } finally {
            Sequel.AutoComitTrue();
        }
    }

    private void ganti() {
        simpan();
    }


    private void loadResep(String pilihan) {
        loading = true;
        tabModeResep.setRowCount(0);
        TNoResep.setText("");
        try {
            ps = koneksi.prepareStatement(
                    "select distinct " + TBL_HEADER + ".no_resep," + TBL_HEADER + ".kd_validasi "
                    + "from " + TBL_HEADER
                    + " inner join resep_obat on resep_obat.no_resep=" + TBL_HEADER + ".no_resep "
                    + "inner join " + TBL_DETAIL + " on " + TBL_DETAIL + ".kd_validasi=" + TBL_HEADER + ".kd_validasi "
                    + "where resep_obat.no_rawat=? order by " + TBL_HEADER + ".no_resep desc");
            try {
                ps.setString(1, TNoRw.getText());
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabModeResep.addRow(new Object[]{rs.getString(1), rs.getString(2)});
                }
            } catch (Exception e) {
                System.out.println("Gagal mengambil daftar resep High Alert: " + e);
                JOptionPane.showMessageDialog(rootPane, "Gagal mengambil daftar resep High Alert:\n" + e.getMessage());
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (Exception e) {
            System.out.println("Gagal menyiapkan daftar resep High Alert: " + e);
            JOptionPane.showMessageDialog(rootPane, "Gagal menyiapkan daftar resep High Alert:\n" + e.getMessage());
        }

        if (tabModeResep.getRowCount() > 0) {
            int barisPilihan = 0;
            if (pilihan != null) {
                for (int r = 0; r < tabModeResep.getRowCount(); r++) {
                    if (pilihan.equals(tabModeResep.getValueAt(r, 0).toString())) {
                        barisPilihan = r;
                        break;
                    }
                }
            }
            tbResep.setRowSelectionInterval(barisPilihan, barisPilihan);
        } else {
            bersihkanValidasi();
        }
        loading = false;
        if (tbResep.getSelectedRow() >= 0) {
            tampil();
        }
    }

    public void tampil() {
        int baris = tbResep.getSelectedRow();
        if (baris < 0) {
            bersihkanValidasi();
            return;
        }
        loading = true;
        TNoResep.setText(tabModeResep.getValueAt(baris, 0).toString());
        kdValidasiTersimpan = tabModeResep.getValueAt(baris, 1).toString();
        tabModeDetail.setRowCount(0);
        Scroll2.setBorder(judulBorder(
                "Detail Obat High Alert - Resep: " + TNoResep.getText()
                + " | Kode Validasi: " + kdValidasiTersimpan));
        TKeterangan.setText("");
        grpInstruksi.clearSelection();
        cekPasien.setSelected(false);
        cekObat.setSelected(false);
        cekDosis.setSelected(false);
        cekRutePemberian.setSelected(false);
        cekFrekuensi.setSelected(false);
        aturPetugas();
        try {
            ps = koneksi.prepareStatement(
                    "select keterangan_kegiatan, nip_petugas2, obat_sesuai_instruksi, "
                    + "cek_pasien, cek_obat, cek_dosis, cek_rute_pemberian, cek_frekuensi "
                    + "from " + TBL_HEADER + " where kd_validasi=?");
            try {
                ps.setString(1, kdValidasiTersimpan);
                rs = ps.executeQuery();
                if (rs.next()) {
                    TKeterangan.setText(rs.getString(1) == null ? "" : rs.getString(1));
                    String nipPetugas2 = rs.getString(2);
                    if (nipPetugas2 == null || nipPetugas2.trim().isEmpty()) {
                        aturPetugas();
                    } else {
                        KdPetugas.setText(nipPetugas2);
                        NmPetugas.setText(Sequel.cariIsi(
                                "select petugas.nama from petugas where petugas.nip=?", nipPetugas2));
                    }
                    grpInstruksi.clearSelection();
                    if ("sesuai".equals(rs.getString(3))) {
                        rbSesuai.setSelected(true);
                    } else if ("perubahan_dosis".equals(rs.getString(3))) {
                        rbPerubahanDosis.setSelected(true);
                    }
                    cekPasien.setSelected(rs.getBoolean(4));
                    cekObat.setSelected(rs.getBoolean(5));
                    cekDosis.setSelected(rs.getBoolean(6));
                    cekRutePemberian.setSelected(rs.getBoolean(7));
                    cekFrekuensi.setSelected(rs.getBoolean(8));
                }
            } catch (Exception e) {
                System.out.println("Gagal memuat validasi resep: " + e);
                JOptionPane.showMessageDialog(rootPane, "Gagal memuat validasi resep:\n" + e.getMessage());
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (Exception e) {
            System.out.println("Gagal menyiapkan detail validasi resep: " + e);
            JOptionPane.showMessageDialog(rootPane, "Gagal menyiapkan detail validasi resep:\n" + e.getMessage());
        }
        tampilDetailObat();
        loading = false;
    }


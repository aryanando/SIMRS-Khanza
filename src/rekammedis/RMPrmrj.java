    private void tampil() {
        Valid.tabelKosong(tabMode);
        try {
            String sql = "select profil_prmrj.no_rawat,profil_prmrj.no_rkm_medis,pasien.nm_pasien,pasien.jk,pasien.tgl_lahir,pasien.no_tlp, "
                    + "profil_prmrj.tanggal,profil_prmrj.diagnosis_penting,profil_prmrj.uraian_klinis_penting,profil_prmrj.rencana_penting, "
                    + "profil_prmrj.riwayat_alergi_obat,profil_prmrj.pengobatan_saat_ini,profil_prmrj.catatan_penting, "
                    + "profil_prmrj.kd_dokter,dokter.nm_dokter "
                    + "from profil_prmrj inner join reg_periksa on profil_prmrj.no_rawat=reg_periksa.no_rawat "
                    + "inner join pasien on profil_prmrj.no_rkm_medis=pasien.no_rkm_medis "
                    + "left join dokter on profil_prmrj.kd_dokter=dokter.kd_dokter "
                    + "where profil_prmrj.tanggal between ? and ? ";
            if (!TCari.getText().equals("")) {
                sql += "and (profil_prmrj.no_rawat like ? or profil_prmrj.no_rkm_medis like ? or pasien.nm_pasien like ? or "
                        + "profil_prmrj.kd_dokter like ? or dokter.nm_dokter like ? or profil_prmrj.diagnosis_penting like ?) ";
            }
            sql += "order by profil_prmrj.tanggal";

            ps = koneksi.prepareStatement(sql);
            try {
                ps.setString(1, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
                ps.setString(2, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));
                if (!TCari.getText().equals("")) {
                    for (int k = 3; k <= 8; k++) {
                        ps.setString(k, "%" + TCari.getText() + "%");
                    }
                }
                rs = ps.executeQuery();
                while (rs.next()) {
                    tabMode.addRow(new Object[]{
                        rs.getString("no_rawat"), rs.getString("no_rkm_medis"), rs.getString("nm_pasien"), rs.getString("jk"),
                        rs.getString("tgl_lahir"), rs.getString("no_tlp"), rs.getString("tanggal"), rs.getString("diagnosis_penting"),
                        rs.getString("uraian_klinis_penting"), rs.getString("rencana_penting"), rs.getString("riwayat_alergi_obat"),
                        rs.getString("pengobatan_saat_ini"), rs.getString("catatan_penting"), rs.getString("nm_dokter")
                    });
                }
            } catch (Exception e) {
                System.out.println("Notif : " + e);
            } finally {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            }
        } catch (SQLException e) {
            System.out.println("Notifikasi : " + e);
        }
        LCount.setText("" + tabMode.getRowCount());
    }


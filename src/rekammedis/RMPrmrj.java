    private void BtnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnPrintActionPerformed
        this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        if (!TCari.getText().trim().equals("")) {
            BtnCariActionPerformed(evt);
        }
        if (tabMode.getRowCount() == 0) {
            JOptionPane.showMessageDialog(null, "Maaf, data sudah habis. Tidak ada data yang bisa anda print...!!!!");
            BtnBatal.requestFocus();
        } else if (tabMode.getRowCount() != 0) {
            Map<String, Object> param = new HashMap<>();
            param.put("namars", akses.getnamars());
            param.put("alamatrs", akses.getalamatrs());
            param.put("kotars", akses.getkabupatenrs());
            param.put("propinsirs", akses.getpropinsirs());
            param.put("kontakrs", akses.getkontakrs());
            param.put("emailrs", akses.getemailrs());
            param.put("logo", Sequel.cariGambar("select setting.logo from setting"));

            String sql = "select profil_prmrj.no_rawat,profil_prmrj.no_rkm_medis,pasien.nm_pasien,pasien.jk,pasien.tgl_lahir,pasien.no_tlp, "
                    + "profil_prmrj.tanggal,profil_prmrj.diagnosis_penting,profil_prmrj.uraian_klinis_penting,profil_prmrj.rencana_penting, "
                    + "profil_prmrj.riwayat_alergi_obat,profil_prmrj.pengobatan_saat_ini,profil_prmrj.catatan_penting, "
                    + "profil_prmrj.kd_dokter,dokter.nm_dokter "
                    + "from profil_prmrj inner join reg_periksa on profil_prmrj.no_rawat=reg_periksa.no_rawat "
                    + "inner join pasien on profil_prmrj.no_rkm_medis=pasien.no_rkm_medis "
                    + "left join dokter on profil_prmrj.kd_dokter=dokter.kd_dokter "
                    + "where profil_prmrj.tanggal between '" + Valid.SetTgl(DTPCari1.getSelectedItem() + "") + "' and '" + Valid.SetTgl(DTPCari2.getSelectedItem() + "") + "' ";

            if (!TCari.getText().trim().equals("")) {
                String kunci = TCari.getText().trim();
                sql += "and (profil_prmrj.no_rawat like '%" + kunci + "%' or profil_prmrj.no_rkm_medis like '%" + kunci + "%' or "
                        + "pasien.nm_pasien like '%" + kunci + "%' or profil_prmrj.kd_dokter like '%" + kunci + "%' or "
                        + "dokter.nm_dokter like '%" + kunci + "%' or profil_prmrj.diagnosis_penting like '%" + kunci + "%') ";
            }
            sql += "order by profil_prmrj.tanggal";

            Valid.MyReportqry("rptDataProfilPrmrj.jasper", "report", "::[ Data Profil Ringkasan Medis Rawat Jalan ]::", sql, param);
        }
        this.setCursor(Cursor.getDefaultCursor());
}//GEN-LAST:event_BtnPrintActionPerformed


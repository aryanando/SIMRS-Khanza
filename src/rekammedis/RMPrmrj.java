    private void simpan() {
        if (TNoRw.getText().trim().equals("") || TNoRM.getText().trim().equals("") || TPasien.getText().trim().equals("")) {
            Valid.textKosong(TNoRw, "Pasien");
        } else if (KdDokter.getText().trim().equals("") || NmDokter.getText().trim().equals("")) {
            Valid.textKosong(KdDokter, "Dokter / DPJP");
        } else {
            if (Sequel.menyimpantf("profil_prmrj", "?,?,?,?,?,?,?,?,?,?", "No.Rawat", 10, new String[]{
                TNoRw.getText(), TNoRM.getText(), Valid.SetTgl(TglPemeriksaan.getSelectedItem() + ""),
                Diagnosa.getText(), RiwayatAlergi.getText(), UraianKlinis.getText(), RencanaPenting.getText(),
                Pengobatan.getText(), Catatan.getText(), KdDokter.getText().trim()
            }) == true) {
                // nama pasien, jk, tgl_lahir, no_hp diambil dari join tabel pasien di tampil()
                tampil();
                emptTeks();
            }
        }
    }

